// Local packaging only: reuse the approved entrypoints and native project.
// Capacitor config remains unchanged on disk; only this sync's in-memory webDir differs.
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync, unlinkSync} from 'node:fs';
import {createRequire} from 'node:module';
import {dirname, resolve, relative} from 'node:path';
import {fileURLToPath} from 'node:url';
import {fingerprint, verifyPrepared} from './android-studio-state.mjs';

const app = resolve(dirname(fileURLToPath(import.meta.url)), '..');
process.chdir(app);
const mode = process.argv[2] ?? 'ui';
assert(['ui', 'live'].includes(mode) && process.argv.length <= 3, 'Use ui or live; no install/start options');
const require = createRequire(import.meta.url);
assert.equal(require('@capacitor/cli/package.json').version, '8.5.3', 'Review the sync adapter after a Capacitor upgrade');
const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
function run(command, args) {
  // cmd.exe is needed for npm.cmd on Windows; all arguments here are fixed literals.
  if (process.platform === 'win32' && command === npm)
    execFileSync('cmd.exe', ['/d', '/s', '/c', [command, ...args].join(' ')], {stdio: 'inherit'});
  else execFileSync(command, args, {stdio: 'inherit'});
}
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
function files(dir, prefix = '') {
  return readdirSync(dir, {withFileTypes: true}).flatMap(e => e.isDirectory()
    ? files(resolve(dir, e.name), prefix + e.name + '/') : [prefix + e.name]);
}
const statePath = resolve(app, '.cache/android-studio/prepared.json');
mkdirSync(dirname(statePath), {recursive: true});
if (existsSync(statePath)) unlinkSync(statePath); // invalidate a previous successful sync
run(npm, ['run', 'verify:consolidation']);
// Do not inherit another terminal's transport flags or DEBUG dump of CLI config.
for (const name of ['SLM_ANDROID_STAGE3', 'SLM_LOCAL_ANDROID', 'SLM_B1_ANDROID', 'SLM_V1_LIVE_LOCAL', 'DEBUG']) delete process.env[name];
if (mode === 'live') {process.env.SLM_ANDROID_STAGE3 = '1'; process.env.SLM_LOCAL_ANDROID = '1';}
run(npm, ['run', mode === 'ui' ? 'build:demo' : 'build:android-stage3']);
const protectedConfig = readFileSync('capacitor.config.ts');
const generatedEol = ['android/capacitor.settings.gradle', 'android/app/capacitor.build.gradle']
  .filter(path => existsSync(path) && readFileSync(path, 'utf8').includes('\r\n'));
// Pinned CLI has no --config switch. Use its actual loadConfig/copy/update API,
// with the same app root and Android directory, rather than a second app/config.
const {loadConfig} = require('@capacitor/cli/dist/config.js');
const {syncCommand} = require('@capacitor/cli/dist/tasks/sync.js');
const config = await loadConfig();
const webDir = mode === 'ui' ? 'dist-demo' : 'dist-android-stage3';
assert.equal(config.app.appId, 'pl.psuda87.slm');
assert.equal(config.android.platformDirAbs, resolve(app, 'android'));
config.app.webDir = webDir;
config.app.webDirAbs = resolve(app, webDir);
config.app.extConfig.webDir = webDir;
assert.equal(config.app.extConfig.loggingBehavior, 'none');
assert.equal(config.app.extConfig.android.webContentsDebuggingEnabled, false);
assert.equal(config.app.extConfig.android.allowMixedContent, mode === 'live');
await syncCommand(config, 'android', false);
// Preserve existing Windows EOL in the two files generated by Capacitor only.
for (const path of generatedEol) writeFileSync(path, readFileSync(path, 'utf8').replace(/\r?\n/g, '\r\n'));
assert.deepEqual(readFileSync('capacitor.config.ts'), protectedConfig, 'Protected config was modified');
const native = resolve(app, 'android/app/src/main/assets');
const copied = resolve(native, 'public');
// sync's copy task can log an error without throwing; verify every source byte.
const sourceFiles = files(config.app.webDirAbs).sort();
for (const name of sourceFiles)
  assert.equal(hash(readFileSync(resolve(copied, name))), hash(readFileSync(resolve(config.app.webDirAbs, name))), 'Stale/missing web asset: ' + name);
const emitted = JSON.parse(readFileSync(resolve(native, 'capacitor.config.json'), 'utf8'));
assert.equal(emitted.webDir, webDir);
assert.equal(emitted.loggingBehavior, 'none');
assert.equal(emitted.android.webContentsDebuggingEnabled, false);
if (mode === 'ui') {
  assert.equal(emitted.android.allowMixedContent, false);
  const headers = JSON.parse(readFileSync('demo/headers.json', 'utf8'));
  // HTTP response headers are unavailable in bundled assets. Preserve the demo's
  // network restriction as a meta policy in the generated native copy only.
  const policy = headers.find(h => h.key === 'Content-Security-Policy').value;
  assert(policy.includes("connect-src 'none'"));
  const index = resolve(copied, 'index.html');
  const html = readFileSync(index, 'utf8');
  writeFileSync(index, html.replace('<head>', '<head>\n<meta http-equiv="Content-Security-Policy" content="' + policy.replaceAll('"', '&quot;') + '">'));
  for (const name of files(copied).filter(n => /\.(html|js|css)$/.test(n)))
    assert(!/supabase\.co|functions\/v1|SessionManager|slm\.auth\.|VITE_SLM_FUNCTION_URL/.test(readFileSync(resolve(copied, name), 'utf8')), 'LIVE code in UI assets: ' + name);
} else {
  const scripts = files(copied).filter(n => n.endsWith('.js')).map(n => readFileSync(resolve(copied, n), 'utf8')).join('\n');
  assert(scripts.includes('http://127.0.0.1:64321/functions/v1/accounts'));
  assert(!scripts.includes('https://hjtcyybkxebvdropchac.supabase.co/functions/v1/accounts'));
}
const assets = Object.fromEntries(files(copied).sort().map(n => [n, hash(readFileSync(resolve(copied, n)))]));
const state = {mode, webDir, inputsSha256: fingerprint(), sourceSha: execFileSync('git', ['rev-parse', 'HEAD'], {encoding: 'utf8'}).trim(),
  preparedUtc: new Date().toISOString(), configSha256: hash(readFileSync(resolve(native, 'capacitor.config.json'))), assets};
writeFileSync(statePath, JSON.stringify(state, null, 2) + '\n');
verifyPrepared();
console.log(`Prepared ${mode.toUpperCase()}: ${sourceFiles.length} verified source assets, ${relative(app, statePath)}. No Docker, APK install or device launch.`);
